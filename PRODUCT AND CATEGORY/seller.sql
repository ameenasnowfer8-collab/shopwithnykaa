##Display Seller + Inventory information

SELECT
    s.Seller_ID,
    s.Seller_Name,
    s.Email,
    i.Product_ID,
    i.Stock_Quantity,
    i.Stock_Status
FROM Seller s
JOIN Inventory i
ON s.Seller_ID = i.Seller_ID;

