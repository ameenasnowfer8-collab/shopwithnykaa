    Seller_ID NUMBER PRIMARY KEY,
    Seller_Name VARCHAR2(100) NOT NULL,
    Email VARCHAR2(100) NOT NULL UNIQUE,
    Contact_No VARCHAR2(15) NOT NULL UNIQUE,
    Address VARCHAR2(200) NOT NULL
);

